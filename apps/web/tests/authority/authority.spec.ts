const database = process.env.TEST_DATABASE_URL!.replace("postgresql+psycopg:","postgresql:");
const parsed = new URL(database);
if (parsed.hostname !== "127.0.0.1" || parsed.username !== "seva_test" || parsed.pathname !== "/seva_phase1_test") throw new Error("Named local synthetic database required");
const pool = new Pool({ connectionString:database,max:2 });
test.beforeEach(async ({context}) => localNetwork(context));
test.afterAll(async () => pool.end());
async function login(page: Page, role: string, target = "/authority/cases") {
  await page.goto(`/sign-in?returnTo=${encodeURIComponent(target)}`);
  await page.getByRole("link",{name:"Continue to secure sign-in"}).click();
  await page.getByLabel("Synthetic resident").selectOption(role);
  await page.getByRole("button",{name:"Continue synthetic sign-in"}).click();
  await expect(page.getByRole("heading",{name:target.startsWith("/resident") ? "Report a concern" : "Case queue",exact:true})).toBeVisible();
}
async function reviewer(browser: Browser, role: string) {
  const context = await browser.newContext({baseURL:process.env.RESIDENT_TEST_WEB_URL,ignoreHTTPSErrors:true,viewport:{width:390,height:844}});
  await localNetwork(context);
  const page = await context.newPage(); await login(page,role); return {context,page};
}
async function mutation(page: Page, action: () => Promise<unknown>) {
  const before = Number(await page.getByTestId("case-revision").textContent());
  await action();
  await expect.poll(async () => Number(await page.getByTestId("case-revision").textContent())).toBeGreaterThan(before);
}

