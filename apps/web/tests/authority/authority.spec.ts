test("unit admin proposes without granting, then revokes a reviewer immediately",async ({browser}) => {
  const resident=await browser.newContext({baseURL:process.env.RESIDENT_TEST_WEB_URL,ignoreHTTPSErrors:true}); await localNetwork(resident); const p=await resident.newPage();
  await login(p,"resident-a","/resident/reports/new");
  const admin=await reviewer(browser,"admin-a"); const member=await reviewer(browser,"reviewer-two");
  const row=(await pool.query("SELECT m.id,m.unit_id,m.user_id FROM unit_memberships m JOIN users u ON u.id=m.user_id WHERE u.issuer=$1 AND u.subject=$2",[process.env.TEST_OIDC_ISSUER,process.env.TEST_REVIEWER_TWO])).rows[0];
  expect((await (await member.page.request.get("/api/app/v2/me")).json()).id).toBe(row.user_id);
  await admin.page.goto(`/authority/unit?unit=${row.unit_id}`);
  await admin.page.getByLabel("Verified identity subject",{exact:true}).fill(process.env.TEST_SUBJECT_A!);
  await admin.page.getByRole("button",{name:"Propose reviewer membership",exact:true}).click();
  await expect(admin.page.getByRole("status",{name:"Membership administration status"})).toContainText("separate operator approval");
  expect((await (await p.request.get("/api/app/v2/me")).json()).units).toEqual([]);
  const suspended=admin.page.waitForResponse((r) => r.url().endsWith(`/memberships/${row.id}/suspend`) && r.request().method() === "POST");
  await admin.page.getByRole("button",{name:`Suspend reviewer ${row.id.slice(0,8)}`,exact:true}).click();
  expect((await suspended).status()).toBe(200);
  expect((await pool.query("SELECT state FROM unit_memberships WHERE id=$1",[row.id])).rows[0].state).toBe("SUSPENDED");
  await expect(admin.page.getByRole("listitem").filter({hasText:new RegExp(`^${row.id.slice(0,8)} · REVIEWER · SUSPENDED`)})).toBeVisible();
  expect((await member.page.request.get(`/api/app/v2/authority/units/${row.unit_id}/cases`)).status()).toBe(404);
  await member.page.reload(); await expect(member.page.getByText("No approved review-unit membership. An invitation request does not grant authority access.")).toBeVisible();
  await admin.context.close(); await member.context.close(); await resident.close();
});
